#!/usr/bin/env python3
"""Write licenses/DEPENDENCIES.md: every third-party crate in the build graph with its licence."""
import json, subprocess, collections, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
meta = json.loads(subprocess.check_output(["cargo", "metadata", "--format-version", "1", "--locked"], cwd=root))
ws = set(meta["workspace_members"])
rows = sorted({(p["name"], p["version"], p.get("license") or "see license file", "vendored" if "/vendor/" in p["manifest_path"] else "crates.io")
               for p in meta["packages"] if p["id"] not in ws})
by = collections.Counter(r[2] for r in rows)
out = ["# Third-party Rust dependencies", "", "Generated by `scripts/gen-dependency-licenses.py`; do not edit by hand.",
       "Full licence texts: crates.io packages ship them in their source archives; vendored ones are in `licenses/vendor/`.", "",
       "## Licence summary", "", "| Licence | Crates |", "|---|---|"]
out += [f"| {l} | {n} |" for l, n in by.most_common()]
out += ["", "## Crates", "", "| Crate | Version | Licence | Source |", "|---|---|---|---|"]
out += [f"| {n} | {v} | {l} | {s} |" for n, v, l, s in rows]
(root / "licenses" / "DEPENDENCIES.md").write_text("\n".join(out) + "\n")
print(len(rows), "crates")
